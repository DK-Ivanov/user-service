package org.aston.cours.service;

import java.util.List;

/**
 * Универсальный сервисный интерфейс для выполнения CRUD-операций над сущностями.
 * <p>
 * Предназначен для реализации базовых операций сохранения, обновления,
 * удаления и поиска данных в хранилище (например, в базе данных).
 * <p>
 * @param <E> тип сущности, над которой выполняются операции
 */
public interface EntityService<E> {

    /**
     * Сохраняет новую сущность в хранилище.
     *
     * @param entity сущность для сохранения
     */
    void save(E entity);

    /**
     * Обновляет существующую сущность в хранилище.
     *
     * @param entity сущность с обновлёнными данными
     */
    void update(E entity);

    /**
     * Удаляет сущность по её уникальному идентификатору.
     *
     * @param id идентификатор сущности
     */
    void delete(int id);

    /**
     * Удаляет сущность по адресу электронной почты.
     *
     * @param email адрес электронной почты сущности
     */
    void delete(String email);

    /**
     * Возвращает список всех сущностей.
     *
     * @return список всех сущностей
     */
    List<E> getAll();

    /**
     * Ищет сущность по её уникальному идентификатору.
     *
     * @param id идентификатор сущности
     * @return найденная сущность или null, если не найдена
     */
    E findById(int id);

    /**
     * Возвращает список сущностей, соответствующих указанному имени.
     *
     * @param name имя, по которому выполняется поиск
     * @return список сущностей с указанным именем
     */
    List<E> findByName(String name);

    /**
     * Ищет сущность по адресу электронной почты.
     *
     * @param email адрес электронной почты
     * @return найденная сущность или null, если не найдена
     */
    E findByEmail(String email);

    /**
     * Возвращает список сущностей, соответствующих указанному возрасту.
     *
     * @param age возраст, по которому выполняется поиск
     * @return список сущностей с указанным возрастом
     */
    List<E> findByAge(int age);
}
